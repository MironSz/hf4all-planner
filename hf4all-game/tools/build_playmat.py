"""Generate data/playmat.js: where things sit on the original playmat graphics.

Reads the Playmat board of the official Vassal module (buildFile.xml, RegionGrid of
the board drawn with fuel_strip.png) and writes, in fuel_strip.png pixels:

- steps[0..56]: the centre of every Fuel Strip position, indexed by black-line step
  (js/fuelstrip.js: step 0 = mass 1, step 56 = mass 32);
- thrust: the Net Thrust track ('<1' = coast only, then 1..15);
- chitStore: the Wet / Dry chit storage circles;
plus the crops of the stack slots in LEO_outposts_freighter.png / Rocket_stack.png /
hand.png (measured from the images).

    python tools/build_playmat.py --download        # module from .cache (see extract_cards.py)
    python tools/build_playmat.py path/to/High_frontier4_1.6.1.vmod

Only coordinates are written (no artwork), so data/playmat.js is kept in git.
"""
import json
import os
import re
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
OUT = os.path.join(GAME, 'data', 'playmat.js')
sys.path.insert(0, HERE)

# Same table as js/fuelstrip.js (fuel steps between integer masses).
INTERVALS = [0, 9, 6, 4, 3, 3, 2, 2, 2, 2, 2] + [1] * 21 + [0]
STEP = [0, 0]
for m in range(2, 33):
    STEP.append(STEP[m - 1] + INTERVALS[m - 1])


def name_to_step(name):
    """'7', '1 4/9', '5-2/3' -> black-line step."""
    m = re.fullmatch(r'(\d+)(?:[ -](\d)/(\d))?', name.strip())
    if not m:
        return None
    mass = int(m.group(1))
    if not 1 <= mass <= 32:
        return None
    if not m.group(2):
        return STEP[mass]
    frac = int(m.group(2)) / int(m.group(3))
    return STEP[mass] + round(frac * INTERVALS[mass])


def main(argv):
    if not argv or argv[0] in ('-h', '--help'):
        print(__doc__)
        return
    if argv[0] == '--download':
        import extract_cards
        vmod = extract_cards.download(os.path.join(GAME, '.cache'))
    else:
        vmod = argv[0]
    xml = zipfile.ZipFile(vmod).read('buildFile.xml').decode('utf-8', errors='replace')
    start = xml.index('<VASSAL.build.module.map.boardPicker.Board image="fuel_strip.png" name="Playmat"')
    block = xml[start:xml.index('</VASSAL.build.module.map.boardPicker.Board>', start)]
    regions = re.findall(r'<VASSAL\.build\.module\.map\.boardPicker\.board\.Region name="([^"]*)" originx="(-?\d+)" originy="(-?\d+)"', block)

    steps, thrust, store = {}, {}, {}
    for name, x, y in regions:
        x, y = int(x), int(y)
        name = name.replace('&lt;', '<')
        if name in ('Wet Mass Chit start', 'Dry Mass Chit start'):
            store[name.split()[0].lower()] = [x, y]
            continue
        if y < 110:                                   # Net Thrust track
            if name == '<1' or re.fullmatch(r'\d+', name):
                thrust[name] = [x, y]
            continue
        if name.startswith(' ') or (x >= 905 and y >= 345) or y > 620:
            continue                                  # Bernal / Kalpana strip, module pieces
        st = name_to_step(name)
        if st is not None and st not in steps:
            steps[st] = [x, y]
    missing = [s for s in range(STEP[32] + 1) if s not in steps]
    if missing:
        sys.exit('Fuel Strip positions not found for steps %s' % missing)
    data = {
        'source': 'Vassal module High_frontier4_1.6.1.vmod, Playmat board (fuel_strip.png)',
        'strip': {'w': 1700, 'h': 880, 'crop': 650, 'mask': [905, 345], 'chit': [71, 35]},
        'steps': [steps[s] for s in range(STEP[32] + 1)],
        'thrust': thrust,
        'chitStore': store,
        'slots': {
            'leo': {'img': 'LEO_outposts_freighter.png', 'iw': 1665, 'ih': 517, 'x': 0, 'w': 548, 'card': 338, 'top': 116,
                    'aquas': [342, 150, 547, 517], 'glories': [376, 30, 481, 135]},
            'rocket': {'img': 'Rocket_stack.png', 'iw': 338, 'ih': 517, 'x': 0, 'w': 338, 'card': 338, 'top': 66},
            'out1': {'img': 'LEO_outposts_freighter.png', 'iw': 1665, 'ih': 517, 'x': 946, 'w': 337, 'card': 337, 'top': 116},
            'out2': {'img': 'LEO_outposts_freighter.png', 'iw': 1665, 'ih': 517, 'x': 1312, 'w': 337, 'card': 337, 'top': 116},
            'hand': {'img': 'hand.png', 'iw': 338, 'ih': 515, 'x': 0, 'w': 338, 'card': 338, 'top': 62}
        }
    }
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* GENERATED by tools/build_playmat.py - positions on the original playmat graphics. */\n')
        f.write('window.HF_PLAYMAT = ' + json.dumps(data, separators=(',', ':')) + ';\n')
    print('wrote %s: %d strip positions, %d thrust spaces' % (OUT, len(steps), len(thrust)))


if __name__ == '__main__':
    main(sys.argv[1:])
