"""Generate hf4all-game/data/map.js from the planner's board data.

One-off developer tool. It only READS planner files:
  ../src/main/resources/data-hf4-v2.json   (node graph)
  ../src/main/resources/static/img/hf4.jpg (board image; used to split the
                                            solarMod=-4 region into the
                                            Saturn / Uranus / Neptune zones)
and writes data/map.js inside this game directory.

Run from anywhere:  python hf4all-game/tools/build_map.py
Requires Pillow (PIL) for the zone colour sampling.
"""
import collections
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
REPO = os.path.dirname(GAME)
SRC_MAP = os.path.join(REPO, 'src', 'main', 'resources', 'data-hf4-v2.json')
SRC_IMG = os.path.join(REPO, 'src', 'main', 'resources', 'static', 'img', 'hf4.jpg')
OUT = os.path.join(GAME, 'data', 'map.js')

W, H = 5400, 3619

# solarMod -> zone for the zones the planner data distinguishes.
ZONE_BY_MOD = {2: 'mercury', 1: 'venus', 0: 'earth', -1: 'mars', -2: 'ceres', -3: 'jupiter'}

# Background colours of the three outer heliocentric bands on the printed map.
OUTER_PALETTE = {
    'saturn': (0x30, 0x32, 0x2d),
    'uranus': (0x2b, 0x2b, 0x47),
    'neptune': (0x14, 0x09, 0x1a),
}


def classify_outer(im, x, y):
    votes = collections.Counter()
    for r in (30, 45, 60, 80):
        for k in range(16):
            a = 2 * math.pi * k / 16
            px = im.getpixel((min(W - 1, max(0, int(x + r * math.cos(a)))),
                              min(H - 1, max(0, int(y + r * math.sin(a))))))
            best = min(OUTER_PALETTE, key=lambda n: sum((px[i] - OUTER_PALETTE[n][i]) ** 2 for i in range(3)))
            if sum((px[i] - OUTER_PALETTE[best][i]) ** 2 for i in range(3)) < 300:
                votes[best] += 1
    return votes.most_common(1)[0][0] if votes else 'saturn'


def main():
    data = json.load(open(SRC_MAP, encoding='utf-8'))
    points = data['points']
    labels = data.get('edgeLabels', {})

    try:
        from PIL import Image
        im = Image.open(SRC_IMG).convert('RGB')
    except Exception as ex:  # pragma: no cover - dev tool
        print('Pillow/board image unavailable, outer zones default to saturn:', ex, file=sys.stderr)
        im = None

    adj = collections.defaultdict(set)
    for e in data['edges']:
        a, b = e.split(':')
        if a in points and b in points:
            adj[a].add(b)
            adj[b].add(a)

    one_way_nodes = set()
    for a, m in labels.items():
        for b, v in m.items():
            if v == '0':
                one_way_nodes.add(a)
                one_way_nodes.add(b)

    nodes = {}
    for nid, p in points.items():
        n = {'x': round(p['x'], 6), 'y': round(p['y'], 6), 't': p['type']}
        mod = p.get('solarMod')
        if mod is None:
            zone = 'mercury'
        elif mod in ZONE_BY_MOD:
            zone = ZONE_BY_MOD[mod]
        else:
            zone = classify_outer(im, p['x'] * W, p['y'] * H) if im else 'saturn'
        n['z'] = zone
        if p.get('siteName'):
            n['name'] = p['siteName']
        if p['type'] == 'site':
            size = p.get('siteSize', '0')
            digits = ''.join(ch for ch in size if ch.isdigit())
            letters = ''.join(ch for ch in size if ch.isalpha())
            n['size'] = int(digits or 0)
            n['spec'] = letters[:1] or 'S'
            n['water'] = int(p.get('siteWater', '0') or 0)
        if p.get('hazard'):
            # Aerobrake hazards sit on the one-way (dashed brown) aerobrake paths;
            # every other hazard is a crash hazard (skull).
            n['haz'] = 'aero' if nid in one_way_nodes else 'crash'
        if 'landing' in p:
            n['land'] = p['landing']
        if p.get('thrustRequired'):
            n['treq'] = p['thrustRequired']
        if p.get('flybyBoost'):
            n['fly'] = p['flybyBoost']
        for src, dst in (('solarOberth', 'oberth'), ('astrobiology', 'astro'), ('submarine', 'sub'),
                         ('atmospheric', 'atmo'), ('push', 'push'), ('centaur', 'centaur')):
            if p.get(src):
                n[dst] = True
        if p.get('synodic'):
            n['syn'] = p['synodic'].lower()
        nodes[nid] = n

    edges = sorted({tuple(sorted((a, b))) for a in adj for b in adj[a]})
    out_labels = {a: {b: v for b, v in m.items() if b in points} for a, m in labels.items() if a in points}

    payload = {
        'source': 'generated by tools/build_map.py from planner data-hf4-v2.json',
        'width': W,
        'height': H,
        'nodes': nodes,
        'edges': [a + ':' + b for a, b in edges],
        'labels': out_labels,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('/* GENERATED FILE - do not edit by hand. Regenerate with tools/build_map.py */\n')
        f.write('window.HF_MAP = ')
        json.dump(payload, f, separators=(',', ':'), ensure_ascii=False)
        f.write(';\n')
    zones = collections.Counter(n['z'] for n in nodes.values())
    print('wrote', OUT, len(nodes), 'nodes', len(edges), 'edges', dict(zones))


if __name__ == '__main__':
    main()
